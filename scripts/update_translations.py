def update_po_file(po_path, trans_dict):
    existing = parse_po(po_path)
    new_entries = []
    
    for msgid, msgstr in trans_dict.items():
        if msgid not in existing:
            safe_id = msgid.replace('\\', '\\\\').replace('"', '\\"')
            safe_str = msgstr.replace('\\', '\\\\').replace('"', '\\"')
            new_entries.append(f'\nmsgid "{safe_id}"\nmsgstr "{safe_str}"\n')
            
    if new_entries:
        with open(po_path, 'a', encoding='utf-8') as f:
            f.writelines(new_entries)
        print(f"Added {len(new_entries)} new translations to {po_path}")
    else:
        print(f"All translations already present in {po_path}")

