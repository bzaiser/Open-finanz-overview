    update_po_file(Path('locale/de/LC_MESSAGES/django.po'), de_translations)
    update_po_file(Path('locale/es/LC_MESSAGES/django.po'), es_translations)
    update_po_file(Path('locale/fr/LC_MESSAGES/django.po'), fr_translations)
    update_po_file(Path('locale/it/LC_MESSAGES/django.po'), it_translations)
    compile_all()
